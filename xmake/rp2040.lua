target("demoapp")
add_files("$(projectdir)/devices/rp2040/device.cpp", "$(projectdir)/devices/rp2040/asm/boot.S")
add_files("$(projectdir)/devices/rp2040/asm/rofs.S")
add_files("$(projectdir)/devices/rp2040/peripherals/timer.cpp")
add_ldflags("-T$(projectdir)/devices/rp2040/link/app.ld", {force = true})

on_load(function (target)
    target:data_set("linkdepfiles", {path.join(os.projectdir(), "devices/rp2040/link/app.ld")})
end)

after_link(function (target)
    local converter = path.join(os.projectdir(), "toolsets", "micronix-make-rp2040-uf2.exe")
    local uf2 = path.join(target:targetdir(), target:basename() .. ".uf2")
    os.vrunv(converter, {target:targetfile(), uf2})
end)
